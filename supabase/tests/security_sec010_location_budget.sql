begin;
set local statement_timeout='30s';
set local plpgsql.check_asserts=on;
do $$
declare a uuid; b uuid; r record; denied boolean; i integer;
begin
  select user_id into a from public.profiles where nickname='kakaoQA' and role='user';
  select user_id into b from public.profiles where nickname='googleQA' and role='user';
  assert a is not null and b is not null and a<>b;
  assert not exists(select 1 from public.location_discovery_rate_limits), 'new_table_fixture_only';
  set local role anon;
  denied:=false;
  begin perform public.claim_location_discovery_budget(a); exception when insufficient_privilege then denied:=true; end;
  assert denied,'anon_budget_denied';
  reset role;
  set local role authenticated;
  denied:=false;
  begin perform public.claim_location_discovery_budget(b); exception when insufficient_privilege then denied:=true; end;
  assert denied,'auth_arbitrary_budget_denied';
  reset role;
  set local role service_role;
  for i in 1..60 loop
    select * into r from public.claim_location_discovery_budget(a);
    assert r.allowed,'caller_normal_allow';
  end loop;
  select * into r from public.claim_location_discovery_budget(a);
  assert not r.allowed and r.retry_after_seconds>0,'caller_minute_denied';
  select * into r from public.claim_location_discovery_budget(b);
  assert r.allowed,'other_caller_not_blocked';
  reset role;
  update public.location_discovery_rate_limits set minute_requests=0,day_requests=500 where user_id=a;
  set local role service_role;
  select * into r from public.claim_location_discovery_budget(a);
  assert not r.allowed,'caller_day_denied';
  reset role;
  update public.location_discovery_rate_limits set day_requests=10000 where bucket_key='global';
  set local role service_role;
  select * into r from public.claim_location_discovery_budget(b);
  assert not r.allowed,'global_day_denied';
  reset role;
  update public.location_discovery_rate_limits set minute_start=now()-interval '2 days',day_start=now()-interval '2 days';
  set local role service_role;
  select * into r from public.claim_location_discovery_budget(a);
  assert r.allowed,'window_reset';
  reset role;
end;
$$;
rollback;
select 'SEC-010 PASS: service-only, per-caller/minute/day and global caps, rollover; rollback complete' as result;
